#!/usr/bin/env python3
"""Copy the ticket-drawing code from the online app into the sample ticket maker.

The online app (vayoraai/shelf-ticket, index.html) is the single source of truth
for how tickets look. This script extracts its ticket functions and ticket CSS,
unchanged, into try-a-ticket/ticket-engine.js and ticket-engine.css. Nothing in
the app is modified. Re-run after changing ticket layout in the app:

    python3 tools/sync-ticket-engine.py /path/to/shelf-ticket/index.html
"""
import re, sys, hashlib, os

src_path = sys.argv[1] if len(sys.argv) > 1 else '../shelf-ticket/index.html'
src = open(src_path, encoding='utf-8').read()
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'try-a-ticket')
digest = hashlib.sha256(src.encode()).hexdigest()[:12]

def between(start, end, inclusive_end=False):
    a = src.index(start)
    b = src.index(end, a)
    return src[a:b + (len(end) if inclusive_end else 0)]

def function(name):
    """Return a top-level `function name(...){...}` block (ends at the first
    line that is exactly '}' after its start — the app's house style)."""
    m = re.search(r'^function ' + re.escape(name) + r'\(', src, re.M)
    if not m: raise SystemExit('function not found: ' + name)
    end = src.index('\n}\n', m.start())
    return src[m.start():end + 2]

# ---- JS ----
parts = [
    re.search(r'^function escapeHtml\(.*$', src, re.M).group(0),
    function('typeConfig'),
    function('shelfSizeClass'),
    function('edgeCell'),
    # buildTicketList … renderBarcodes: one contiguous block in the app
    between('function buildTicketList(', '// The ticket page is built at true A4 size'),
]
js = ('/* GENERATED by tools/sync-ticket-engine.py from the Vayora Tickets app\n'
      ' * (shelf-ticket/index.html, sha256 ' + digest + '). Do not edit by hand.\n'
      ' * Expects globals: settings, $(id), JsBarcode. */\n'
      + '\n'.join(parts))
for needed in ['function shelfTicketHtml', 'function promoTicketHtml', 'function buildPagesHtml',
               'function fitAllTickets', 'function renderBarcodes', 'function renderPrintArea']:
    assert needed in js, needed

# ---- CSS ----
css = between('#printArea{display:none;}', '@media (max-width:720px){ .row2')
css += between('/* Ticket text follows the size of the paper', '</style>')
css = ('/* GENERATED by tools/sync-ticket-engine.py from the Vayora Tickets app\n'
       ' * (sha256 ' + digest + '). Do not edit by hand. */\n' + css)

open(os.path.join(here, 'ticket-engine.js'), 'w', encoding='utf-8').write(js)
open(os.path.join(here, 'ticket-engine.css'), 'w', encoding='utf-8').write(css)
print('ticket engine synced from', src_path, digest, len(js), 'bytes JS,', len(css), 'bytes CSS')
